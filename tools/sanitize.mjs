// Защита бренда: детект мата/вульгарных слов перед публикацией.
// LLM на высокой температуре иногда вставляет вульгаризм вопреки запрету — это ловится здесь,
// генератор делает чистую переписку, и если всё равно грязно — слот пропускается (НИКОГДА не публикуем мат).
// Список — только однозначно вульгарное. В JS \b/\w работают лишь по ASCII и НЕ дают границу
// у кириллицы, поэтому границы слова заданы явными lookbehind/lookahead по буквам — чтобы
// «команда», «хлеб», «худой», «сукно», «хук», «употребление» и т.п. НЕ срабатывали.
const BS = "(?<![а-яёА-ЯЁa-zA-Z])"; // начало слова (перед — не буква)
const BE = "(?![а-яёА-ЯЁa-zA-Z])";  // конец слова (после — не буква)
const HARD = [
  /пизд/i,                                            // пизда, пиздец
  /бля[дть]/i,                                        // блядь, блять, бляди (не «наблюдать»,«обляпать»)
  /ёб/i,                                              // ёбан, заёб, долбоёб
  /дроч/i,                                            // дрочить
  /залуп/i,
  /г[ао]ндон/i,                                       // гандон, гондон
  /пид[оа]р/i,                                        // пидор, пидар
  /долбо[её]б/i,
  /муд(ак|ил|охон)/i,                                 // мудак, мудила (не «мудрый»)
  /(вы|за|на|у|про|об|до|пере|подъ|разъ|съ)[её]б/i,   // выеб, заёб, наеб, уеб
  new RegExp(BS + "ху[йеёяю]", "i"),                  // хуй, хуе, хуё, хуя, хую (не «хук»,«худой»,«хутор»)
  new RegExp(BS + "(на|по|до|ни)ху[йеёяю]?", "i"),    // нахуй, похую, дохуя, нихуя
  new RegExp(BS + "еб[аеёлоуыий]", "i"),              // ебать, ебло (не «хлеб»,«потреб»)
  new RegExp(BS + "сук[аи]" + BE, "i"),               // сука, суки (не «сукно»,«сукин»)
  new RegExp(BS + "сучк", "i"),                       // сучка
  new RegExp(BS + "манда" + BE, "i"),                 // манда (не «команда»)
];

// Вернуть список найденных вульгаризмов (для лога). Пусто — текст чистый.
export function findProfanity(text) {
  const s = String(text || "");
  const hits = [];
  for (const re of HARD) {
    const m = s.match(re);
    if (m) hits.push(m[0]);
  }
  return [...new Set(hits)];
}

export const hasProfanity = (text) => findProfanity(text).length > 0;

// CLI: node tools/sanitize.mjs "<text>"  → печатает найденное (для отладки)
if (import.meta.url === `file://${process.argv[1]}`) {
  const hits = findProfanity(process.argv.slice(2).join(" "));
  console.log(hits.length ? "НАЙДЕНО: " + hits.join(", ") : "чисто");
  process.exit(hits.length ? 2 : 0);
}
